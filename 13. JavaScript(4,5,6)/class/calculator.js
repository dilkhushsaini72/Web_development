const calculator = {
  add: function (a, b) {
    return a + b;
  },
  sub: function (a, b) {
    return a - b;
  },
  mul: function (a, b) {
    return a * b;
  },
  div: function (a, b) {
    return a / b;
  },
};


console.log(calculator.add(8, 5));
console.log(calculator.sub(8, 5));
console.log(calculator.mul(8, 5));
console.log(calculator.div(8, 5));